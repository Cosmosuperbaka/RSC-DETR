"""M3FD dual-stream detection dataset.

M3FD stores paired visible and infrared images with matching file stems under
separate modality roots. The COCO JSON generated by scripts/m3fd uses the
visible relative path as image.file_name and stores the matching IR relative
path in image.ir_file_name.
"""

import os
from PIL import Image

from .coco_dataset import CocoDetection
from ...core import register


__all__ = ['M3FDDetection']


@register()
class M3FDDetection(CocoDetection):
    """Dual-stream COCO-format dataset for M3FD.

    __getitem__ returns ((visible_pil, infrared_pil), target). The transform
    pipeline must be a DualCompose instance.
    """

    __inject__ = ['transforms']
    __share__ = []

    def __init__(self, img_folder, ann_file, transforms, return_masks=False, ir_folder=None):
        super().__init__(
            img_folder=img_folder,
            ann_file=ann_file,
            transforms=transforms,
            return_masks=return_masks,
            remap_mscoco_category=False,
        )
        self.ir_folder = ir_folder if ir_folder is not None else img_folder

    def __getitem__(self, idx):
        rgb_pil, target = self.load_item(idx)
        image_id = self.ids[idx]
        img_info = self.coco.loadImgs(image_id)[0]
        ir_relpath = img_info.get('ir_file_name')
        if not ir_relpath:
            rgb_relpath = img_info['file_name']
            stem, ext = os.path.splitext(os.path.basename(rgb_relpath))
            ir_relpath = stem + ext

        ir_path = os.path.join(self.ir_folder, ir_relpath)
        if not os.path.exists(ir_path):
            raise FileNotFoundError(f'IR image not found: {ir_path}')
        ir_pil = Image.open(ir_path).convert('RGB')

        if self._transforms is not None:
            (rgb_pil, ir_pil), target, _ = self._transforms((rgb_pil, ir_pil), target, self)
        return (rgb_pil, ir_pil), target

    def extra_repr(self) -> str:
        s = f' img_folder: {self.img_folder}\n ir_folder:  {self.ir_folder}\n'
        s += f' ann_file:   {self.ann_file}\n return_masks: {self.return_masks}\n'
        if hasattr(self, '_transforms') and self._transforms is not None:
            s += f' transforms:\n   {repr(self._transforms)}'
        return s
